#!/usr/bin/env node
// create-opencapx-plugin — one command produces an installable plugin scaffold (zero deps, Node standard library only).
//   node scripts/create-opencapx-plugin.mjs --id com.acme.hello [--name "Hello"] [--author acme] [--license MIT] [--dir ./hello] [--template <dir>]
// id rules match Core's valid_plugin_id: charset [a-z0-9.-], no "..", no leading/trailing dot, ≤128.
import { cpSync, existsSync, readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { dirname, join, resolve } from "node:path";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");

function usage(exitCode) {
  console.error(
    'usage: node scripts/create-opencapx-plugin.mjs --id <reverse.dns.id> [--name "Name"] [--author "Your Name"] [--license MIT] [--dir <target>] [--template <dir>]',
  );
  process.exit(exitCode);
}

const args = {};
const argv = process.argv.slice(2);
for (let i = 0; i < argv.length; i++) {
  const a = argv[i];
  if (a === "--help" || a === "-h") usage(0);
  if (!a.startsWith("--")) usage(2);
  const val = argv[++i];
  if (val === undefined) usage(2);
  args[a.slice(2)] = val;
}

const id = args.id;
if (!id) usage(2);
if (
  !/^[a-z0-9.-]{1,128}$/.test(id) ||
  id.includes("..") ||
  id.startsWith(".") ||
  id.endsWith(".")
) {
  console.error(
    `invalid id: ${id} (charset [a-z0-9.-], no "..", no leading/trailing dot, max 128 chars)`,
  );
  process.exit(2);
}

function pascal(s) {
  const name = s
    .split(/[-_]/)
    .filter(Boolean)
    .map((p) => p[0].toUpperCase() + p.slice(1))
    .join("");
  if (!name) return "My";
  return /^[0-9]/.test(name) ? `P${name}` : name;
}

const lastSegment = id.split(".").pop();
const name = args.name ?? pascal(lastSegment);
const author = args.author ?? "your-name";
const license = args.license ?? "MIT";
const target = resolve(args.dir ?? `./${lastSegment}`);
const template = resolve(args.template ?? join(root, "plugin-template"));

if (!existsSync(template)) {
  console.error(`template not found: ${template}`);
  process.exit(2);
}
if (existsSync(target)) {
  console.error(`target already exists: ${target} (refusing to overwrite)`);
  process.exit(1);
}

cpSync(template, target, { recursive: true });

const manifestPath = join(target, "opencapx-plugin.json");
const manifest = JSON.parse(readFileSync(manifestPath, "utf8"));
manifest.id = id;
manifest.name = name;
manifest.author = author;
manifest.license = license;
manifest.description = `${name}: generated by create-opencapx-plugin; replace this with your plugin description.`;
writeFileSync(manifestPath, `${JSON.stringify(manifest, null, 2)}\n`);

const className = `${pascal(lastSegment)}Plugin`;
const pyPath = join(target, "bin", "plugin.py");
let py = readFileSync(pyPath, "utf8");
py = py.replace(
  '"""OpenCapX plugin template: a minimal capability plugin (based on opencapx_sdk).',
  `"""${name}: a minimal capability plugin (based on opencapx_sdk).`,
);
py = py.replaceAll("MyPlugin", className);
writeFileSync(pyPath, py);

const readmePath = join(target, "README.md");
const readme = readFileSync(readmePath, "utf8").replace("# OpenCapX plugin template", `# ${name}`);
writeFileSync(readmePath, readme);

console.log(`✓ ${name} (${id}) → ${target}`);
console.log("  next steps:");
console.log("    1. edit bin/plugin.py to implement your capability logic, and check the opencapx-plugin.json capabilities/permissions");
console.log("    2. package and verify locally: opencapx pack . --key <seed-hex> --key-id <keyId> --out dist/plugin.ocplugin");
console.log("       opencapx verify-package dist/plugin.ocplugin   # F10 auto-gate pre-run");
console.log("    3. push a v* tag → GitHub Actions automatically packs + signs + attaches the release (see README)");
