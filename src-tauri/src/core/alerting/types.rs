/// Phase 51 — DSL RouteRule DTO used by the frontend (`when` + `then`).
#[derive(Debug, Clone, Serialize, Deserialize)]
#[serde(rename_all = "camelCase")]
pub struct RouteRule {
    #[serde(default)]
    pub id: String,
    pub name: String,
    #[serde(default = "default_route_priority")]
    pub priority: i32,
    #[serde(default = "default_route_enabled")]
    pub enabled: bool,
    #[serde(default = "default_kind_pattern")]
    pub kind_pattern: String,
    #[serde(default)]
    pub payload_path: Option<String>,
    #[serde(default)]
    pub payload_match: Option<String>,
    /// Phase 51 — legacy field, references a WebhookEndpoint id.
    /// Since Phase 66 prefer `recipients` (supports webhook / log:stderr / log:file / email:smtp).
    /// Kept for backward compatibility: when recipients is empty, fall back to `["webhook:{id}" for id in target_endpoint_ids]`.
    #[serde(default)]
    pub target_endpoint_ids: Vec<String>,
    /// Phase 66 — multi-channel recipient refs (each spec resolved by `notification::resolve_recipient`).
    #[serde(default)]
    pub recipients: Vec<String>,
    #[serde(default)]
    pub tags: Vec<String>,
    /// Phase 68 — temporal correlation condition: only when an event matching `pattern` occurred within the past `window_secs`
    /// does this route fan out. `None` means unconditional fanout.
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub seen_in_last: Option<SeenInLastSpec>,
}

/// Phase 68 — Route temporal correlation condition.
/// `pattern` uses Phase 51's `kind_matches` glob (`*` / `**.*`).
#[derive(Debug, Clone, Serialize, Deserialize)]
#[serde(rename_all = "camelCase")]
pub struct SeenInLastSpec {
    pub pattern: String,
    pub window_secs: u64,
}

fn default_route_priority() -> i32 {
    100
}

fn default_route_enabled() -> bool {
    true
}

/// Phase 51 — YAML import/export top-level format:
/// ```yaml
/// version: 1
/// rules:
///   - name: critical → ops
///     priority: 10
///     when:
///       kind_pattern: "plugin.metrics.*"
///       payload_path: "cpu_percent"
///       payload_match: ">=90"
///     then:
///       target_endpoint_ids: ["ep-oncall"]
///       tags: ["p1", "page"]
/// ```
#[derive(Debug, Clone, Serialize, Deserialize)]
#[serde(rename_all = "camelCase")]
pub struct RouteRuleYamlDoc {
    #[serde(default = "default_yaml_version")]
    pub version: u32,
    pub rules: Vec<RouteRule>,
}

fn default_yaml_version() -> u32 {
    1
}

